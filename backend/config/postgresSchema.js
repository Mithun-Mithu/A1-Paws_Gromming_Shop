
export const schema = `
CREATE TABLE IF NOT EXISTS admins (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email TEXT NOT NULL UNIQUE,
  password_hash TEXT NOT NULL,
  role TEXT NOT NULL DEFAULT 'admin',
  token_version INTEGER NOT NULL DEFAULT 0,
  full_name TEXT NOT NULL DEFAULT '',
  phone TEXT NOT NULL DEFAULT '',
  status TEXT NOT NULL DEFAULT 'active',
  created_at TEXT NOT NULL DEFAULT ''
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_admin_email_case_insensitive
ON admins (LOWER(email));

CREATE TABLE IF NOT EXISTS customers (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name TEXT NOT NULL,
  phone TEXT NOT NULL,
  email TEXT
);

CREATE TABLE IF NOT EXISTS pets (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id INTEGER NOT NULL REFERENCES customers(id),
  name TEXT NOT NULL,
  type TEXT NOT NULL,
  breed TEXT,
  age TEXT,
  size TEXT
);

CREATE TABLE IF NOT EXISTS services (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  description TEXT DEFAULT '',
  price INTEGER NOT NULL CHECK (price >= 0),
  duration INTEGER NOT NULL CHECK (duration > 0),
  active INTEGER NOT NULL DEFAULT 1,
  image_url TEXT NOT NULL DEFAULT ''
);

CREATE TABLE IF NOT EXISTS bookings (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  reference TEXT NOT NULL UNIQUE,
  customer_id INTEGER NOT NULL REFERENCES customers(id),
  pet_id INTEGER NOT NULL REFERENCES pets(id),
  appointment_date TEXT NOT NULL,
  start_time TEXT NOT NULL,
  end_time TEXT NOT NULL,
  total_price INTEGER NOT NULL,
  total_duration INTEGER NOT NULL,
  payment_method TEXT NOT NULL,
  payment_status TEXT NOT NULL DEFAULT 'pending',
  status TEXT NOT NULL DEFAULT 'pending',
  notes TEXT,
  created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  assigned_admin_id INTEGER REFERENCES admins(id) ON DELETE SET NULL,
  additional_charges INTEGER NOT NULL DEFAULT 0,
  discount_amount INTEGER NOT NULL DEFAULT 0,
  final_amount INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS booking_services (
  booking_id INTEGER NOT NULL REFERENCES bookings(id) ON DELETE CASCADE,
  service_id INTEGER NOT NULL REFERENCES services(id),
  service_name TEXT NOT NULL,
  price INTEGER NOT NULL,
  duration INTEGER NOT NULL,
  PRIMARY KEY (booking_id, service_id)
);

CREATE TABLE IF NOT EXISTS business_hours (
  weekday INTEGER PRIMARY KEY,
  is_open INTEGER NOT NULL,
  open_time TEXT NOT NULL,
  close_time TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS holidays (
  date TEXT PRIMARY KEY,
  label TEXT DEFAULT ''
);

CREATE TABLE IF NOT EXISTS payments (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  booking_id INTEGER NOT NULL REFERENCES bookings(id),
  provider TEXT NOT NULL,
  amount INTEGER NOT NULL,
  status TEXT NOT NULL,
  created_at TEXT DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS admin_password_resets (
  admin_id INTEGER PRIMARY KEY REFERENCES admins(id) ON DELETE CASCADE,
  otp_hash TEXT,
  otp_salt TEXT,
  expires_at BIGINT,
  last_sent_at BIGINT NOT NULL,
  attempts INTEGER NOT NULL DEFAULT 0,
  reset_token_hash TEXT,
  reset_expires_at BIGINT
);

CREATE TABLE IF NOT EXISTS admin_audit_log (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor_admin_id INTEGER REFERENCES admins(id) ON DELETE SET NULL,
  target_admin_id INTEGER REFERENCES admins(id) ON DELETE SET NULL,
  action TEXT NOT NULL,
  details TEXT NOT NULL DEFAULT '{}',
  created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS contact_numbers (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  label TEXT NOT NULL,
  country_code TEXT NOT NULL,
  phone_number TEXT NOT NULL,
  call_enabled INTEGER NOT NULL DEFAULT 1 CHECK (call_enabled IN (0,1)),
  whatsapp_enabled INTEGER NOT NULL DEFAULT 1 CHECK (whatsapp_enabled IN (0,1)),
  whatsapp_message TEXT NOT NULL DEFAULT 'Hello A1 PAWS! I would like to enquire about your pet grooming services and appointment availability.',
  is_primary INTEGER NOT NULL DEFAULT 0 CHECK (is_primary IN (0,1)),
  status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active','inactive')),
  created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CHECK (is_primary = 0 OR status = 'active'),
  UNIQUE (country_code, phone_number)
);

CREATE INDEX IF NOT EXISTS idx_admin_audit_created_at
ON admin_audit_log(created_at);

CREATE INDEX IF NOT EXISTS idx_bookings_assigned_admin
ON bookings(assigned_admin_id);

CREATE INDEX IF NOT EXISTS idx_bookings_date
ON bookings(appointment_date);

CREATE INDEX IF NOT EXISTS idx_bookings_phone
ON customers(phone);

CREATE UNIQUE INDEX IF NOT EXISTS idx_contact_numbers_single_primary
ON contact_numbers(is_primary)
WHERE is_primary = 1;
`;
